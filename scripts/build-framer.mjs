// build-framer.mjs — joins each Framer component into the single file Framer needs.
//
// Framer's code files can't import each other, so the code is organised in folders here
// and joined for Framer: starting from a component's entry file, every "./" or "../"
// import is pasted in once (the files it imports come first), the react, react-dom and
// framer imports are merged into one each, and `export` is dropped, except the
// component's own `export default`. Everything ends up in one scope, so two files
// declaring the same name stop the build with a clear error.
//
// Run with:  npm run build:framer
// Output:    framer-build/<Component>.tsx — generated, don't edit; save it to Framer.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative, resolve } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
export const COMPONENTS = ["framer/dashboard/Dashboard.tsx", "framer/calendar/MonthCalendar.tsx"]
const IMPORT = /^import\s+([\s\S]*?)\s+from\s+"([^"]+)"\s*;?[ \t]*\n/gm
const DECLARATION = /^(?:export\s+)?(?:default\s+)?(?:async\s+)?(?:function|const|let|class|interface|type|enum)\s+([A-Za-z_$][\w$]*)/gm

// Where a component's joined file goes: framer-build/<Component>.tsx
export const outputOf = (entry) => join(ROOT, "framer-build", entry.split("/").pop())

// Run directly (npm run build:framer): write the files. Imported (by the tests): just
// lend build() and the paths, so the tests can check framer-build/ is up to date.
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  for (const entry of COMPONENTS) {
    const out = build(join(ROOT, entry))
    const target = outputOf(entry)
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, out)
    console.log(`${relative(ROOT, target).replace(/\\/g, "/")}  ←  ${entry}  (${out.split("\n").length} lines)`)
  }
}

export function build(entryPath) {
  const order = []                       // files in the order they're pasted
  const seen = new Set()
  const external = new Map()             // module → its imported names, in first-seen order

  function visit(path, chain) {
    if (chain.includes(path)) throw new Error(`Import loop: ${[...chain, path].map((p) => relative(ROOT, p)).join(" → ")}`)
    if (seen.has(path)) return
    seen.add(path)
    const text = readFileSync(path, "utf8")
    for (const [, names, from] of text.matchAll(IMPORT)) {
      if (from.startsWith(".")) visit(resolve(dirname(path), from), [...chain, path])
      else {
        const list = external.get(from) ?? []
        for (const name of names.replace(/[{}]/g, "").split(",").map((n) => n.trim()).filter(Boolean))
          if (!list.includes(name)) list.push(name)
        external.set(from, list)
      }
    }
    order.push({ path, text })
  }
  visit(entryPath, [])

  // One scope: every top-level name must be declared once.
  const declared = new Map()
  for (const { path, text } of order) {
    for (const [, name] of text.matchAll(DECLARATION)) {
      if (declared.has(name)) {
        throw new Error(`"${name}" is declared in both ${relative(ROOT, declared.get(name))} and ${relative(ROOT, path)}; rename one.`)
      }
      declared.set(name, path)
    }
  }

  // A name imported as a type in one file and as a value in another is a value.
  const imports = [...external].map(([from, names]) => {
    const values = new Set(names.filter((n) => !n.startsWith("type ")))
    const merged = names.filter((n) => !(n.startsWith("type ") && values.has(n.slice(5))))
    return `import { ${merged.join(", ")} } from "${from}"`
  })

  const parts = order.map(({ path, text }) => {
    let body = text.replace(IMPORT, "")
    body = path === entryPath ? body.replace(/^export (?!default)/gm, "") : body.replace(/^export /gm, "")
    return `// ── ${relative(ROOT, path).replace(/\\/g, "/")} ${"─".repeat(Math.max(4, 72 - relative(ROOT, path).length))}\n\n${body.trim()}\n`
  })

  return [
    `// GENERATED by scripts/build-framer.mjs from ${relative(ROOT, entryPath).replace(/\\/g, "/")} and the files it imports.`,
    "// Don't edit this file: edit those files and run `npm run build:framer`.",
    "",
    ...imports,
    "",
    parts.join("\n"),
  ].join("\n")
}
